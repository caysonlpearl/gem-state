UPDATE public.classified_listing_details d
SET city = p.city, region = p.region
FROM idaho_place_regions p
WHERE upper(btrim(coalesce(d.state, ''))) = 'ID'
  AND lower(regexp_replace(coalesce(d.city, ''), '[^A-Za-z]', '', 'g')) = p.key
  AND (d.city IS DISTINCT FROM p.city OR d.region IS DISTINCT FROM p.region);

UPDATE public.fb_marketplace_import_items i
SET city = p.city, region = p.region, state = 'ID'
FROM idaho_place_regions p
WHERE upper(btrim(coalesce(i.state, ''))) IN ('ID', 'IDAHO')
  AND lower(regexp_replace(coalesce(i.city, ''), '[^A-Za-z]', '', 'g')) = p.key
  AND (i.city IS DISTINCT FROM p.city OR i.region IS DISTINCT FROM p.region OR i.state <> 'ID');

