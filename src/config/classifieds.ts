classifiedCityNamesByKey.set("sandy", "Sandy, UT");

export function classifiedCoordinatesForCity(city: string | undefined, state?: string) {
  if (!city) return undefined;
  const trimmedCity = city.trim();
  const cityState = trimmedCity.match(/^(.+),\s*(.+)$/);
  const embeddedState = cityState?.[2]?.trim();
  const recognizedEmbeddedState = embeddedState
    ? usStates.find(
        ([code, name]) =>
          code.toLowerCase() === embeddedState.toLowerCase() ||
          name.toLowerCase() === embeddedState.toLowerCase(),
      )
    : undefined;
  const cityName = recognizedEmbeddedState ? cityState?.[1]?.trim() || trimmedCity : trimmedCity;
  // A qualified selector such as "Sandy, OR" is the chosen center even if a
  // stale/default state filter is still present in the URL.
  const stateToken = (recognizedEmbeddedState?.[0] ?? state)?.trim();
  const stateCode = stateToken
    ? (usStates
        .find(
          ([code, name]) =>
            code.toLowerCase() === stateToken.toLowerCase() ||
            name.toLowerCase() === stateToken.toLowerCase(),
        )?.[0]
        .toLowerCase() ?? stateToken.toLowerCase())
    : undefined;
  const stateSpecificCenter = stateCode
    ? classifiedCityCenters[`${cityName.toLowerCase()}, ${stateCode}`]
    : undefined;
  return stateSpecificCenter ?? classifiedCityCenters[cityName.toLowerCase()];
}

export function nearestClassifiedCity(latitude: number, longitude: number) {
  let nearest: { city: string; distanceMiles: number } | undefined;
  for (const [key, point] of Object.entries(classifiedCityCenters)) {
    const distanceMiles = classifiedDistanceMiles(latitude, longitude, point[0], point[1]);
    if (!nearest || distanceMiles < nearest.distanceMiles) {
      nearest = { city: classifiedCityNamesByKey.get(key) ?? key, distanceMiles };
    }
  }
  return nearest;
}

export function classifiedDistanceMiles(
  latitude: number,
  longitude: number,
  targetLatitude: number,
  targetLongitude: number,
) {
  const toRadians = (value: number) => (value * Math.PI) / 180;
  const dLat = toRadians(targetLatitude - latitude);
  const dLon = toRadians(targetLongitude - longitude);
  const lat1 = toRadians(latitude);
  const lat2 = toRadians(targetLatitude);
  const a = Math.sin(dLat / 2) ** 2 + Math.cos(lat1) * Math.cos(lat2) * Math.sin(dLon / 2) ** 2;
  return 3958.8 * 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
}

export function isWithinClassifiedRadius({
  city,
  cityState,
  listingCity,
  listingState,
  latitude,
  longitude,
  radiusMiles,
}: {
  city?: string;
  cityState?: string;
  listingCity: string;
  listingState?: string;
  latitude?: number;
  longitude?: number;
  radiusMiles?: number;
}) {
  if (radiusMiles == null) return true;
  const center =
    latitude != null && longitude != null
      ? ([latitude, longitude] as [number, number])
      : classifiedCoordinatesForCity(city, cityState);
  const point = classifiedCoordinatesForCity(listingCity, listingState);
  if (!center || !point) {
    const normalizeCity = (value: string | undefined) =>
      value
        ?.trim()
        .replace(/,\s*[a-z]{2}$/i, "")
        .toLowerCase();
    return normalizeCity(listingCity) === normalizeCity(city);
  }
  return classifiedDistanceMiles(center[0], center[1], point[0], point[1]) <= radiusMiles;
}

export function isWithinClassifiedCityRadius(
  city: string | undefined,
  listingCity: string,
  radiusMiles: number | undefined,
) {
  return isWithinClassifiedRadius({ city, listingCity, radiusMiles });
}

