/** A state is only a location-center hint when the search has a real radius center. */
export function hasClassifiedRadiusCenter({
  city,
  latitude,
  longitude,
  radiusMiles,
}: {
  city?: string;
  latitude?: number;
  longitude?: number;
  radiusMiles?: number;
}) {
  return radiusMiles != null && (Boolean(city?.trim()) || (latitude != null && longitude != null));
}

