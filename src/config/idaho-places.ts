const placeKey = (value: string) => value.toLowerCase().replace(/[^a-z]/g, "");
const placesByKey = new Map(idahoPlaces.map((place) => [placeKey(place[0]), place]));

/** The listed Idaho place a typed city name means, ignoring case, spacing and
 * punctuation ("coeur dalene" -> Coeur d'Alene), or undefined. */
